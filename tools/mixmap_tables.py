#!/usr/bin/env python3
"""Emit `3DS Files/source/mixmap_tables.h`: NFSMixShape's three lookup tables, and
bASin's, which SFXCTL_3DObjPos aims the mix map's 3D controls with.

They are read from `Gamecube Files/Speed.elf` (big-endian 32-bit words) by symbol name:

    g_dBToQ15XForm    602 words  GetQ15FromHundredthsdB (0x800b592c): Q15 mantissa of
                                 one 6.02 dB octave, 0x4000 .. 0x7fff
    g_Q15todBXForm    512 words  GetdBFromQ15 (0x800b599c): hundredths of a dB of a
                                 9-bit mantissa, 0 .. 601
    g_nArrayCosTable  513 words  GetCurveOutput (0x800b5aec) curves 0 and 4: a quarter
                                 cosine, 0x7fff .. 0, plus one guard entry
    bASinTable        209 entries bASin (0x800594c8): {u16 bAngle, u16 0, float slope}

The first three fit 16 bits, so the header stores them as uint16_t.

usage: python tools/mixmap_tables.py
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gc_disasm as g  # noqa: E402

TABLES = (
    ("g_dBToQ15XForm", "kMixDbToQ15", 602),
    ("g_Q15todBXForm", "kMixQ15ToDb", 512),
    ("g_nArrayCosTable", "kMixCos", 513),
)

# bASin (0x800594c8), which SFXCTL_3DObjPos::SetCameraAngle turns a dot product
# into a bAngle with: x in 1/65536ths, split into 12 segments that halve toward
# x = 1 (where the arcsine steepens), 16 entries each, plus a guard run.
ASIN_SYM = "bASinTable"
ASIN_COUNT = 209

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "3DS Files", "source", "mixmap_tables.h")


def main():
    data, secs = g.load()
    syms = g.symbols(data, secs)
    lines = [
        "// Generated by tools/mixmap_tables.py from Speed.elf -- do not edit.",
        "// NFSMixShape's lookup tables (GetQ15FromHundredthsdB 0x800b592c,",
        "// GetdBFromQ15 0x800b599c, GetCurveOutput 0x800b5aec), and bASin's (0x800594c8).",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for sym, cname, count in TABLES:
        va, size = syms[sym]
        assert size == count * 4, (sym, size)
        off = g.va_to_off(secs, va)
        vals = struct.unpack_from(">%di" % count, data, off)
        assert all(0 <= v <= 0xFFFF for v in vals), sym
        lines.append("// %s, %d entries" % (sym, count))
        lines.append("static const uint16_t %s[%d] = {" % (cname, count))
        for i in range(0, count, 12):
            lines.append("    " + ", ".join("0x%04x" % v for v in vals[i:i + 12]) + ",")
        lines.append("};")
        lines.append("")
    # bASinTable: per entry a u16 bAngle, a u16 pad and a float slope.
    va, size = syms[ASIN_SYM]
    assert size == ASIN_COUNT * 8, (ASIN_SYM, size)
    off = g.va_to_off(secs, va)
    lines.append("// %s, %d entries: the bAngle at the entry's x and the slope after it" % (ASIN_SYM, ASIN_COUNT))
    lines.append("typedef struct { uint16_t angle; float slope; } MixASinEntry;")
    lines.append("static const MixASinEntry kMixASin[%d] = {" % ASIN_COUNT)
    ents = [struct.unpack_from(">HHf", data, off + 8 * i) for i in range(ASIN_COUNT)]
    assert all(pad == 0 for _a, pad, _s in ents)
    for i in range(0, ASIN_COUNT, 4):
        lines.append("    " + " ".join("{ 0x%04x, %.9gf }," % (a, s) for a, _p, s in ents[i:i + 4]))
    lines.append("};")
    lines.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
