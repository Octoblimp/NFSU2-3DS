#!/usr/bin/env python3
"""Emit `3DS Files/source/engine_tables.h`: the player engine sound's static tables,
read from `PC Files/SPEED2.EXE` (little-endian 32-bit words) by address.

PC data needs the PC tables: the GC twins (g_SND_ENGINE_DATA, ...) are a different
build of the same structs, and the PC's CarPreSetup (0x4593b0) picks the dual Ginsu
mix the GC never uses.

    ENGINE_DATA       0x7f0de0  43 x 0x4c  per engine: banks, accel .gin, Ginsu / AEMS mix
    DUAL_GINSU        0x7f1aa8  37 x 0x34  the decel .gin and its mix
    CARDATAMAPPING    0x7f2230  33 x 4 levels x {engine, shift pattern, turbo}
    SHIFTPATTERNS     0x7f2860  18 x 0x60  SFXCTL_Shifting's per-gearbox timings
    SWEETNERDATASET   0x7f3040  43 x 3     CARSFX_Shift's SWTN bank, by engine
    ACCELFROMIDLE     0x7f3248  12 x 5     SFXCTL_AccelTrans's launch from idle
    TURBODATASET      0x7f3338  15 x 6     CARSFX_Turbo's bank and spool
    g_nArrayCosTable  0x7ef7f8  513 ints   a quarter cosine, 32767 .. 0 (the GC's
                                           0x803585CC holds the same 513)
    g_SKID_PARAMS     0x7f2f20  4 x 0x48   SFXCTL_Skid's GenerateSkidNoise: car, car
                                           drifting, truck, truck drifting (the GC's
                                           0x803A7810 is .bss, filled at boot)
    SKID_QUIET_TERRAIN_TYPE_SCALE 0x7ed240 CARSFX_Skids' level on grass and water
    GetCarTypeMapping 0x459240  a switch, car type 0..30 -> CARDATAMAPPING row (jump
                                table 0x45930c, one `mov eax, imm; ret` per case)

usage: python tools/engine_tables.py
"""
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.path.join(os.environ.get("NFSU2_PC_ROOT") or os.path.join(ROOT, "PC Files"), "SPEED2.EXE")
OUT = os.path.join(ROOT, "3DS Files", "source", "engine_tables.h")

ENGINE_DATA, N_ENGINE = 0x7f0de0, 43
DUAL_GINSU, N_DUAL = 0x7f1aa8, 37
CARDATAMAPPING, N_MAPPING = 0x7f2230, 33
SHIFTPATTERNS, N_SHIFT = 0x7f2860, 18
ACCELFROMIDLE, N_ACCEL = 0x7f3248, 12
SWEETNERDATASET, N_SWEETENER = 0x7f3040, 43
TURBODATASET, N_TURBO = 0x7f3338, 15
COS_TABLE, N_COS = 0x7ef7f8, 513
SKID_PARAMS, N_SKID = 0x7f2f20, 4
SKID_QUIET_SCALE = 0x7ed240
GET_CAR_TYPE_MAPPING = 0x459240   # mov eax, [esp+4]; cmp eax, 0x1e; ja default; jmp [table]
CAR_TYPE_JUMPS, N_CAR_TYPES = 0x45930c, 31
CAR_TYPE_DEFAULT_CASE = 0x459305

TAB = "\t"


class Exe:
    def __init__(self, path):
        self.d = open(path, "rb").read()
        d = self.d
        pe = struct.unpack_from("<I", d, 0x3c)[0]
        nsec = struct.unpack_from("<H", d, pe + 6)[0]
        opt = struct.unpack_from("<H", d, pe + 20)[0]
        self.base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
        self.secs = []
        for i in range(nsec):
            o = pe + 24 + opt + 40 * i
            vs, va, rs, ro = struct.unpack_from("<IIII", d, o + 8)
            self.secs.append((va, rs, ro))

    def off(self, v):
        for va, rs, ro in self.secs:
            if self.base + va <= v < self.base + va + rs:
                return ro + v - self.base - va
        raise ValueError("VA %x not in the file" % v)

    def u32(self, v):
        return struct.unpack_from("<I", self.d, self.off(v))[0]

    def i32(self, v):
        return struct.unpack_from("<i", self.d, self.off(v))[0]

    def f32(self, v):
        return struct.unpack_from("<f", self.d, self.off(v))[0]

    def cstr(self, v):
        o = self.off(self.u32(v))
        s = self.d[o:self.d.index(b"\0", o)].decode("ascii")
        assert s.isprintable() and s, hex(v)
        return s

    def case_value(self, v):
        # A case stub: `xor eax, eax; ret` or `mov eax, imm32; ret`.
        o = self.off(v)
        if self.d[o:o + 3] == bytes((0x33, 0xc0, 0xc3)):
            return 0
        assert self.d[o] == 0xb8 and self.d[o + 5] == 0xc3, hex(v)
        return struct.unpack_from("<i", self.d, o + 1)[0]


def fl(x):
    # The shortest decimal that rounds back to the same float32.
    bits = struct.pack("<f", x)
    if x == int(x) and abs(x) < 1e7:
        return "%d.0f" % x
    for p in range(1, 10):
        r = "%.*g" % (p, x)
        if struct.pack("<f", float(r)) == bits:
            break
    return r + "f" if ("e" in r or "." in r) else r + ".0f"


HEADER = """// Generated by tools/engine_tables.py from SPEED2.EXE -- do not edit.
// The player engine sound's tables: ENGINE_DATA 0x7f0de0, DUAL_GINSU 0x7f1aa8,
// CARDATAMAPPING 0x7f2230, SHIFTPATTERNS 0x7f2860, ACCELFROMIDLE 0x7f3248,
// GetCarTypeMapping's switch (0x459240), and the shift and turbo SFX's:
// SWEETNERDATASET 0x7f3040, TURBODATASET 0x7f3338, g_nArrayCosTable 0x7ef7f8,
// and the skids': g_SKID_PARAMS 0x7f2f20, SKID_QUIET_TERRAIN_TYPE_SCALE 0x7ed240.
#pragma once
#include <stdint.h>

typedef struct {
	const char* eeBank;     // +0x00 the PS2 bank name; the PC loads the SPU one
	const char* spuBank;    // +0x04 the AEMS CAR bank
	int32_t     id;         // +0x08 the AEMS CAR instance's engine
	const char* gin;        // +0x0C the accel .gin
	int32_t     dual;       // +0x10 has a decel .gin
	int32_t     dualIdx;    // +0x14 its kDualGinsu entry
	int32_t     accelIdx;   // +0x18 its kAccelFromIdle entry
	float       ginMaxRpm;  // +0x1C the Ginsu RPM at sound RPM 10000
	float       ginMinRpm;  // +0x20 ... and at 1000
	int32_t     aemsVol;    // +0x24
	int32_t     ginVol;     // +0x28
	float       dRpmNorm;   // +0x2C the RPM change per frame that is all "on"
	float       aemsOn;     // +0x30
	float       ginOn;      // +0x34
	float       aemsBase;   // +0x38
	float       ginBase;    // +0x3C
	float       aemsOff;    // +0x40
	float       ginOff;     // +0x44
	int32_t     lowpassMin; // +0x48
} EngineData;

typedef struct {
	const char* gin;        // +0x00 the decel .gin
	int32_t     aemsVol0;   // +0x04 the AEMS volume at no torque
	int32_t     ginVol;     // +0x08
	int32_t     graphLo;    // +0x0C the decel graph's ends, Ginsu RPM
	int32_t     graphHi;    // +0x10
	float       graphFall;  // +0x14
	float       graphRise;  // +0x18
	float       dRpmNorm;   // +0x1C
	int32_t     unused;     // +0x20 always 0
	float       aemsOn;     // +0x24
	float       ginOn;      // +0x28
	float       aemsBase;   // +0x2C
	float       ginBase;    // +0x30
} DualGinsuData;

// One SHIFTPATTERNS entry: word 0 is its GEAR bank, then 23 words that
// SFXCTL_Shifting reads by byte offset; +0x08, +0x20, +0x40 and +0x5C are floats.
typedef union { int32_t i; float f; } ShiftWord;
typedef struct {
	const char* bank;
	ShiftWord   w[23];      // +0x04 .. +0x5C
} ShiftPattern;
#define SHIFT_I(p, off) ((p)->w[(off) / 4 - 1].i)
#define SHIFT_F(p, off) ((p)->w[(off) / 4 - 1].f)

typedef struct {
	float   vol;            // +0x00
	int32_t rpmAdd;         // +0x04
	int32_t msBegin;        // +0x08
	int32_t msSettle;       // +0x0C state 3
	int32_t msRelease;      // +0x10 state 4
} AccelFromIdle;

typedef struct {
	const char* bank;       // +0x00 the SWTN_CAR bank, in ENGINE
	int32_t     vol;        // +0x04 the gear-change rasp's level
	int32_t     vol2;       // +0x08 (CARSFX_Shift does not read it)
} SweetenerData;

typedef struct {
	const char* bank;       // +0x00 the TURBO bank
	int32_t     spoolVol;   // +0x04 the spool's level at full boost
	int32_t     blowVol1;   // +0x08 the blow-off's level, type 1
	int32_t     blowVol2;   // +0x0C ... types 2 and 3
	float       maxSpool;   // +0x10 the spool's full scale
	float       decay;      // +0x14 its fall a frame off the boost
} TurboData;

// One g_SKID_PARAMS set, which SFXCTL_Skid::GenerateSkidNoise reads. "Right"
// and "left" are the car's two sides, each the sum of its two wheels.
typedef struct {
	float   spinScale;      // +0x00 a side's wheel spin (slip forward) to skid
	float   spinMax;        // +0x04 ... clamped to this
	float   spinMin;        // +0x08 ... and this, the bottom of the 0..1024 scale
	float   lockScale;      // +0x0C a braking side's lateral slip to skid
	float   lockMax;        // +0x10
	float   lockMin;        // +0x14
	int32_t backUp;         // +0x18 the sliding-backwards level's rise a frame
	int32_t backDown;       // +0x1C ... and fall
	float   backMix;        // +0x20 its share of the braking skid
	float   unused;         // +0x24
	float   gripLimit;      // +0x28 a tyre's grip use past which it slides
	float   gripTime;       // +0x2C ... for this long, s
	int32_t slideUp;        // +0x30 the sideways slide's rise a frame
	int32_t slideDown;      // +0x34 ... and fall
	float   slideMix;       // +0x38 its share of the slide skid
	float   yawSide;        // +0x3C the trailing side's share of the yaw
	float   yawLo;          // +0x40 the yaw, rad, at which the slide begins ...
	float   yawHi;          // +0x44 ... and is all slide
} SkidParams;
"""


def main():
    x = Exe(EXE)
    L = HEADER.split("\n")
    L += ["// A file that only needs the types defines ENGINE_TABLES_TYPES_ONLY first,",
          "// so the tables are compiled once (carsfx.c).",
          "#ifndef ENGINE_TABLES_TYPES_ONLY", ""]

    L.append("static const EngineData kEngineData[%d] = {" % N_ENGINE)
    for i in range(N_ENGINE):
        e = ENGINE_DATA + i * 0x4c
        assert 0 <= x.i32(e + 0x14) < N_DUAL and 0 <= x.i32(e + 0x18) < N_ACCEL, i
        L.append(TAB + '{ "%s", "%s", %d, "%s", %d, %d, %d, %s, %s, %d, %d, %s, %s, %d },' % (
            x.cstr(e), x.cstr(e + 4), x.i32(e + 8), x.cstr(e + 0xc),
            x.i32(e + 0x10), x.i32(e + 0x14), x.i32(e + 0x18),
            fl(x.f32(e + 0x1c)), fl(x.f32(e + 0x20)), x.i32(e + 0x24), x.i32(e + 0x28),
            fl(x.f32(e + 0x2c)),
            ", ".join(fl(x.f32(e + k)) for k in range(0x30, 0x48, 4)), x.i32(e + 0x48)))
    L += ["};", ""]

    L.append("static const DualGinsuData kDualGinsu[%d] = {" % N_DUAL)
    for i in range(N_DUAL):
        e = DUAL_GINSU + i * 0x34
        L.append(TAB + '{ "%s", %d, %d, %d, %d, %s, %s, %s, %d, %s },' % (
            x.cstr(e), x.i32(e + 4), x.i32(e + 8), x.i32(e + 0xc), x.i32(e + 0x10),
            fl(x.f32(e + 0x14)), fl(x.f32(e + 0x18)), fl(x.f32(e + 0x1c)), x.i32(e + 0x20),
            ", ".join(fl(x.f32(e + k)) for k in range(0x24, 0x34, 4))))
    L += ["};", ""]

    L.append("// [row][level 0..3] = { kEngineData by the engine level, kShiftPatterns by the")
    L.append("// gearbox level, kTurboData by the turbo level }")
    L.append("static const int8_t kCarDataMapping[%d][4][3] = {" % N_MAPPING)
    for r in range(N_MAPPING):
        cells = []
        for lv in range(4):
            t = [x.i32(CARDATAMAPPING + (r * 12 + lv * 3 + k) * 4) for k in range(3)]
            assert 0 <= t[0] < N_ENGINE and 0 <= t[1] < N_SHIFT and 0 <= t[2] < N_TURBO, (r, lv, t)
            cells.append("{ %d, %d, %d }" % tuple(t))
        L.append(TAB + "{ %s }," % ", ".join(cells))
    L += ["};", ""]

    floats = {2, 8, 16, 23}   # the words at +0x08, +0x20, +0x40, +0x5C
    L.append("static const ShiftPattern kShiftPatterns[%d] = {" % N_SHIFT)
    for i in range(N_SHIFT):
        e = SHIFTPATTERNS + i * 0x60
        ws = []
        for k in range(1, 24):
            if k in floats:
                ws.append("{ .f = %s }" % fl(x.f32(e + 4 * k)))
            else:
                ws.append("{ .i = %d }" % x.i32(e + 4 * k))
        L.append(TAB + '{ "%s", { %s } },' % (x.cstr(e), ", ".join(ws)))
    L += ["};", ""]

    L.append("static const AccelFromIdle kAccelFromIdle[%d] = {" % N_ACCEL)
    for i in range(N_ACCEL):
        e = ACCELFROMIDLE + i * 20
        L.append(TAB + "{ %s, %d, %d, %d, %d }," % (
            fl(x.f32(e)), x.i32(e + 4), x.i32(e + 8), x.i32(e + 12), x.i32(e + 16)))
    L += ["};", ""]

    L.append("static const SweetenerData kSweetener[%d] = {" % N_SWEETENER)
    for i in range(N_SWEETENER):
        e = SWEETNERDATASET + i * 12
        L.append(TAB + '{ "%s", %d, %d },' % (x.cstr(e), x.i32(e + 4), x.i32(e + 8)))
    L += ["};", ""]

    L.append("static const TurboData kTurboData[%d] = {" % N_TURBO)
    for i in range(N_TURBO):
        e = TURBODATASET + i * 24
        L.append(TAB + '{ "%s", %d, %d, %d, %s, %s },' % (
            x.cstr(e), x.i32(e + 4), x.i32(e + 8), x.i32(e + 12),
            fl(x.f32(e + 16)), fl(x.f32(e + 20))))
    L += ["};", ""]

    cos = [x.i32(COS_TABLE + 4 * i) for i in range(N_COS)]
    assert cos[0] == 32767 and cos[-1] == 0 and cos == sorted(cos, reverse=True)
    L.append("// g_nArrayCosTable: index 0..512, 32767 down to 0.")
    L.append("static const int32_t kCosTable[%d] = {" % N_COS)
    for i in range(0, N_COS, 16):
        L.append(TAB + ", ".join(str(v) for v in cos[i:i + 16]) + ",")
    L += ["};", ""]

    ints = {6, 7, 12, 13}   # the words at +0x18, +0x1C, +0x30, +0x34
    L.append("// [truck ? 2 : 0 | drifting], SFXCTL_Skid::SetupCTL's pick.")
    L.append("static const SkidParams kSkidParams[%d] = {" % N_SKID)
    for i in range(N_SKID):
        e = SKID_PARAMS + i * 0x48
        ws = [str(x.i32(e + 4 * k)) if k in ints else fl(x.f32(e + 4 * k)) for k in range(18)]
        assert all(0 < x.i32(e + 4 * k) < 100 for k in ints), i
        L.append(TAB + "{ %s }," % ", ".join(ws))
    L += ["};", ""]
    quiet = x.i32(SKID_QUIET_SCALE)
    assert 0 < quiet < 0x8000, quiet
    L += ["enum { SKID_QUIET_TERRAIN_TYPE_SCALE = %d };" % quiet, ""]

    o = x.off(GET_CAR_TYPE_MAPPING)
    assert x.d[o + 4:o + 7] == bytes((0x83, 0xf8, 0x1e)), "GetCarTypeMapping moved"
    rows = [x.case_value(x.u32(CAR_TYPE_JUMPS + 4 * i)) for i in range(N_CAR_TYPES)]
    dflt = x.case_value(CAR_TYPE_DEFAULT_CASE)
    assert all(0 <= r < N_MAPPING for r in rows + [dflt])
    L.append("// GetCarTypeMapping (0x459240): car type -> kCarDataMapping row.")
    L.append("static const int8_t kCarTypeMapping[%d] = {" % N_CAR_TYPES)
    L.append(TAB + ", ".join(str(v) for v in rows))
    L += ["};", "enum { CAR_TYPE_MAPPING_DEFAULT = %d };" % dflt, "",
          "#endif // ENGINE_TABLES_TYPES_ONLY", ""]

    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(L))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
